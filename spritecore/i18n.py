def set_lang(code):
    """언어와 그에 맞는 기본 글꼴을 지정한다."""
    global LANG, UI_FONT
    LANG = code if code in LANG_CODES else "ko"
    UI_FONT = FONTS[LANG]


def t(key, **kw):
    """번역 문자열. 표에 없으면 한국어 원문을 그대로 쓴다."""
    text = TRANSLATIONS.get(LANG, {}).get(key, key)
    return text.format(**kw) if kw else text


